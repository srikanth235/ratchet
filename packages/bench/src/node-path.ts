import { accessSync, chmodSync, constants, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, delimiter, dirname, join } from 'node:path';

/**
 * Evaluator, setup and guardrail commands are shell strings such as `node dist/eval/backtest.js`. They
 * need a `node` on PATH that works, and two things break that:
 *  - inside the packaged Electron app (launched from the Dock) PATH is the bare launchd PATH and has no
 *    node at all;
 *  - `process.execPath` there is the Electron binary, which only behaves like Node with
 *    `ELECTRON_RUN_AS_NODE=1` in its environment.
 * `withNodeOnPath` fixes both by putting a directory with a `node` executable first on PATH.
 */

/** What the fix depends on; a parameter (not read from `process`) so tests can simulate Electron. */
export interface NodeRuntimeInfo {
  /** `process.execPath`. */
  execPath: string;
  /** `process.versions.electron`; set only when running inside Electron. */
  electron?: string | undefined;
  /** `process.platform`. Anything but win32 is treated as POSIX. */
  platform?: NodeJS.Platform | undefined;
}

export function currentNodeRuntime(): NodeRuntimeInfo {
  return { execPath: process.execPath, electron: process.versions['electron'], platform: process.platform };
}

const shq = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`;

/** Body of the `node` shim. Under Electron the variable is set for that one process only, not exported to anything else. */
export function nodeShimScript(execPath: string, electron: boolean): string {
  return [
    '#!/bin/sh',
    '# Generated by Ratchet: makes `node` resolve to the runtime that is running the app.',
    `${electron ? 'ELECTRON_RUN_AS_NODE=1 ' : ''}exec ${shq(execPath)} "$@"`,
    '',
  ].join('\n');
}

const shimDirs = new Map<string, string>();

/**
 * A directory holding an executable `node` shim for `execPath`. It is created once per process under a
 * fresh random directory (mode 0700, so nobody can pre-plant a `node` in a predictable /tmp path) and
 * removed when the process exits.
 */
export function ensureNodeShim(execPath: string, electron: boolean, shimRoot: string = tmpdir()): string {
  const key = `${shimRoot}\0${execPath}\0${electron}`;
  const known = shimDirs.get(key);
  if (known) {
    try {
      accessSync(join(known, 'node'), constants.X_OK);
      return known;
    } catch {
      shimDirs.delete(key); // removed behind our back (tmp cleaner): recreate
    }
  }
  const dir = mkdtempSync(join(shimRoot, 'ratchet-node-'));
  const file = join(dir, 'node');
  writeFileSync(file, nodeShimScript(execPath, electron), { mode: 0o755 });
  chmodSync(file, 0o755);
  shimDirs.set(key, dir);
  process.once('exit', () => {
    try {
      rmSync(dir, { recursive: true, force: true });
    } catch {
      /* best effort */
    }
  });
  return dir;
}

/** The `node` that `pathEnv` would resolve (symlinks resolved), or undefined. */
export function resolveNodeOnPath(pathEnv: string): string | undefined {
  for (const dir of pathEnv.split(delimiter)) {
    if (dir === '') continue;
    const candidate = join(dir, 'node');
    try {
      accessSync(candidate, constants.X_OK);
      return realpathSync(candidate);
    } catch {
      /* not here */
    }
  }
  return undefined;
}

/**
 * The directory to put first on PATH so that `node` runs this runtime, or undefined when PATH is
 * already fine:
 *  - Electron: always a shim that execs the Electron binary with `ELECTRON_RUN_AS_NODE=1`;
 *  - plain Node whose binary is called `node`: `dirname(execPath)`, unless the first `node` on PATH
 *    already is that binary (then PATH is left alone, so tools in that directory cannot shadow others);
 *  - plain Node under another name (`node22`, ...): a shim, so `node` exists at all.
 */
export function nodeDirFor(runtime: NodeRuntimeInfo, pathEnv: string, shimRoot?: string): string | undefined {
  if ((runtime.platform ?? process.platform) === 'win32') return undefined;
  if (runtime.electron) return ensureNodeShim(runtime.execPath, true, shimRoot);
  let self: string;
  try {
    self = realpathSync(runtime.execPath);
  } catch {
    self = runtime.execPath;
  }
  if (resolveNodeOnPath(pathEnv) === self) return undefined;
  if (basename(runtime.execPath) === 'node') return dirname(runtime.execPath);
  return ensureNodeShim(runtime.execPath, false, shimRoot);
}

export interface WithNodeOnPathOptions {
  runtime?: NodeRuntimeInfo;
  /** Where shim directories are created. Default: the OS temp dir. */
  shimRoot?: string;
  /** PATH to extend when `env` has none. Default: `process.env.PATH`. */
  basePath?: string | undefined;
}

/** `env` with `PATH` prefixed so that `node` works. Entries with undefined values are dropped. Does not mutate `env`. */
export function withNodeOnPath(env: Record<string, string | undefined> = {}, opts: WithNodeOnPathOptions = {}): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(env)) if (v !== undefined) out[k] = v;
  const base = out['PATH'] ?? opts.basePath ?? process.env['PATH'] ?? '';
  const dir = nodeDirFor(opts.runtime ?? currentNodeRuntime(), base, opts.shimRoot);
  if (dir === undefined) return out;
  out['PATH'] = base === '' ? dir : `${dir}${delimiter}${base}`;
  return out;
}
