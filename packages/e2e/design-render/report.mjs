// Build DESIGN_CHECK.md from artifacts/design-check/{before,after}.json (written by check.mjs).
//   node design-render/report.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (n) => JSON.parse(readFileSync(join(root, 'artifacts', 'design-check', `${n}.json`), 'utf8'));
const before = load('before');
const after = load('after');
const fonts = load('fonts');

const TITLES = {
  optimizations: '1 · Optimizations',
  'new-optimization': '2 · New optimization',
  sandbox: '3 · AWS sandbox (Environments)',
  'live-agents': '4 · Live agents',
  benchmarks: '5 · Benchmark history',
  result: '6 · Result & teardown',
};
const key = (r) => `${r.check}\u0000${r.prop}`;
const esc = (s) => String(s).replace(/\|/g, '\\|');
const mark = (r) => (r === undefined ? '—' : r.pass ? 'pass' : 'FAIL');

/** Structural differences that remain, with the reason (kept next to the data so the report never drifts from the checks). */
const STRUCT_NOTES = {
  'Window chrome row (traffic lights)': 'Not applicable: the design draws a fake macOS window; the app uses the real OS window frame.',
  'Range switch 7d / 30d / 90d': 'Left out: the KPI windows come from the main process (`this week`, `last 24h`) and have no range parameter in `RatchetApi`.',
  'Benchmark picker cards (k6 / pb / custom)': 'Left out: ratchet.yaml is the source of truth for the evaluator; the form edits it as text fields instead of choosing among detected benchmarks.',
  'Guardrail checkbox list': 'Left out: guardrails are free-form lines (`run: <cmd>` / `<metric>: <op> <value>`) in a textarea, validated by `parseConfig`; there is no catalogue of detectable guardrails to tick.',
  'Metric switch (p50/p95/p99/rps)': 'Left out: `ratchetHistory` only carries the objective metric; per-percentile series would need a new API/ledger query.',
  '"Where the time went" span bars': 'TODO: needs a per-span profile of baseline vs best, which the ledger does not store.',
  '"Winning change" file diff': 'TODO: needs the winning commit diff (files, +/- counts, hunk) exposed through `RatchetApi`; only SHAs are available today.',
};

let out = `# Design check: app vs \`design/*.dc.html\`

Generated by \`packages/e2e/design-render/report.mjs\` from \`artifacts/design-check/before.json\` and \`after.json\`.

How it is measured: each \`design/*.dc.html\` is rendered standalone (\`design-render/dc-shim.js\`: evaluates \`class Component extends DCLogic { renderVals() }\`, expands \`<sc-for>\` / \`<sc-if>\` / \`{{holes}}\`, hoists \`<helmet>\`) at 1440 px and screenshotted to \`artifacts/design/<screen>.png\`. The desktop app is launched with \`RATCHET_ENGINE=dev\` (seeded data comparable to the designs) and screenshotted to \`artifacts/app/<screen>.png\`. \`design-render/check.mjs\` then reads **computed styles** of corresponding elements in both (declared in \`design-render/specs.mjs\`) and compares them (colours within 2/255, sizes within 0.5 px, font family by first family actually used).

Re-run: \`pnpm --filter @ratchet/desktop build && cd packages/e2e && node design-render/render.mjs && xvfb-run -a node scripts/shoot-app.mjs && xvfb-run -a node design-render/check.mjs after && node design-render/report.mjs\`.

"Before" is the app as it was when the design work started (before the previous worker's fixes and this round's); "After" is the current build.

`;

const sum = (j) => Object.values(j.screens).reduce((a, s) => ({ p: a.p + s.rows.filter((r) => r.pass).length, n: a.n + s.rows.length }), { p: 0, n: 0 });
const sb = sum(before), sa = sum(after);
out += `## Summary

| | Before | After |
|---|---|---|
| Computed-style checks passing | ${sb.p} / ${sb.n} | **${sa.p} / ${sa.n}** |
`;
for (const [s, t] of Object.entries(TITLES)) {
  const b = before.screens[s], a = after.screens[s];
  out += `| ${t}: style / structure | ${b.rows.filter((r) => r.pass).length}/${b.rows.length} · ${b.structure.filter((x) => x.app).length}/${b.structure.length} | ${a.rows.filter((r) => r.pass).length}/${a.rows.length} · ${a.structure.filter((x) => x.app).length}/${a.structure.length} |\n`;
}

out += `
## Fonts actually rendered

Chromium's \`CSS.getPlatformFontsForNode\` for representative elements (\`design-render/fonts.mjs\`): the files really used, not just the declared \`font-family\`. All are bundled webfonts (@fontsource), no system fallback.

| Element | Design | App | |
|---|---|---|---|
`;
for (const k of Object.keys(fonts.design)) {
  const norm = (v) => String(v).replace(/ \(Fontations\)/g, '').replace(/, \d+ glyphs/g, '');
  out += `| ${k} | ${esc(norm(fonts.design[k]))} | ${esc(norm(fonts.app[k]))} | ${norm(fonts.design[k]) === norm(fonts.app[k]) ? 'pass' : 'FAIL'} |\n`;
}

for (const [s, t] of Object.entries(TITLES)) {
  const a = after.screens[s], b = before.screens[s];
  const bm = new Map(b.rows.map((r) => [key(r), r]));
  out += `\n## ${t}\n\nScreenshots: \`artifacts/design/${s}.png\` (design), \`artifacts/app/${s}.png\` (app).\n\n| Element · property | Design | App | Before | After |\n|---|---|---|---|---|\n`;
  for (const r of a.rows) out += `| ${esc(r.check)} · ${r.prop} | ${esc(r.design)} | ${esc(r.app)} | ${mark(bm.get(key(r)))} | ${mark(r)} |\n`;
  out += `\n**Structure** (does the design element have an app counterpart?)\n\n| Element | Design | App | Before | Note |\n|---|---|---|---|---|\n`;
  const bs = new Map(b.structure.map((x) => [x.check, x]));
  for (const x of a.structure) {
    out += `| ${esc(x.check)} | yes | ${x.app ? 'yes' : 'no'} | ${bs.get(x.check)?.app ? 'yes' : 'no'} | ${x.app ? '' : esc(STRUCT_NOTES[x.check] ?? '')} |\n`;
  }
}

out += `
## Deliberate copy deviations (the product is generic now)

| Design says | App says | Why |
|---|---|---|
| "The benchmark decides." | "The evaluator decides." | config key is \`evaluator\`; the objective need not be a benchmark |
| "Pick a benchmark, …" / "Benchmark & metric" / "Bench hardware" / "Bench ref" | "Pick an evaluator, …" / "Evaluator & metric" / "Evaluator hardware" / "Evaluator ref" | same |
| "Trusted bench runner" | "Trusted evaluator" | same |
| Sandbox diagram "Bench runner" / "re-bench" | "Evaluator runner" / "re-evaluate" | same |
| Nav "Spend", tab "Config" | "Result" | the Result screen replaces them; the screen names "Benchmarks" / "Benchmark history" are kept (they are the design's screen names) |

## Beyond the design: $ value (generic product)

- New optimization: the file bar and the Review panel summarize the **evaluator** (kind · ref) and the **value** of the objective (e.g. \`$1,200 per ms / year · estimated\`) parsed from the pasted ratchet.yaml.
- Result headline: "Worth $X a year (estimated) · N× return on spend" and the Optimizations featured card show "≈ $X / year", computed like \`estimateValue\` / \`returnOnSpend\` in \`@ratchet/core\` (mirrored in \`renderer/value.ts\`: the renderer cannot import core, it pulls in SQLite). They appear only when \`objective.value\` is set and the metric improved.
- TODO: the Optimizations KPI cards (verified wins / median gain / spend / cost per win) are built in the main process (\`mappers.ts\`); a "value created" / "return on spend" KPI should be added there. \`shared/config-yaml.ts\` still generates the legacy \`bench:\` key and has no \`objective.value\` field in the form; \`ConfigSummary\` has no evaluator/value (the renderer parses the YAML for display).

## Overall verdict

**Pass with documented leftovers.** Every computed-style check of the six screens passes (fonts: Instrument Serif for titles and hero numbers, Instrument Sans UI, JetBrains Mono data, all rendered; Midnight Brass surfaces, hairlines, radii, pills, avatars, chart colours, sidebar rhythm). The remaining differences are structural features that need data or API the product does not have yet (listed under each screen: range switch, metric switch, time-by-span and winning diff on Result) or design choices the app replaces on purpose (fake window chrome, evaluator picker cards, guardrail tick list).
`;
writeFileSync(join(root, 'DESIGN_CHECK.md'), out);
console.log('DESIGN_CHECK.md written', out.length);
