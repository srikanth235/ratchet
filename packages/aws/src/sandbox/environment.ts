import { copyFile, mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, posix } from 'node:path';
import {
  DEFAULT_ENVIRONMENT_INFRA_DIR,
  SANDBOX_BASE_MODULE_NAME,
  validateEnvironment,
  type SandboxEnvironment,
  type SandboxEnvironmentOutputs,
} from '@ratchet/core';
import { LOCAL_EXEC, InfraOverrideError } from './override.js';
import type { AwsSandboxOutputs } from './tofu.js';

/**
 * Materializing an approved environment for OpenTofu (docs/SIMPLIFIED_MODEL.md, "Dynamic environments").
 *
 * The engine reads the environment's files from the PROTECTED ref and hands them over in `SandboxInput.environment`; nothing
 * here touches git. Two kinds:
 *
 *  - `custom` (`infra:` in ratchet.yaml, advanced): the module REPLACES the standard one. Written to a directory of its own,
 *    refused when it can run commands, and its outputs are checked against infra/contract.md after every apply.
 *  - `drafted` (`environment.scope` full / single with OpenTofu): a second stage on top of the standard sandbox. The directory
 *    holds the draft's files, a copy of the base module Ratchet ships (`ratchet-sandbox/`) and two generated files the draft may
 *    not contain: the provider / `ratchet` variable (`ratchet_inputs.tf`) and the `environment` output (`ratchet_outputs.tf`).
 *    The drafted files are validated again (`validateEnvironment`, the same allow-list the user saw) before anything is written.
 */

export class EnvironmentRejectedError extends Error {
  constructor(readonly problems: string[]) {
    super(
      `the environment does not satisfy the sandbox contract:\n - ${problems.join('\n - ')}\n` +
        'Draft it again (the setup agent can revise it), or remove environment.scope / infra from ratchet.yaml to use the standard sandbox.',
    );
    this.name = 'EnvironmentRejectedError';
  }
}

/** Generated next to every drafted environment; the draft may not ship files with these names. */
export const GENERATED_INPUTS_FILE = 'ratchet_inputs.tf';
export const GENERATED_OUTPUTS_FILE = 'ratchet_outputs.tf';
/** Directory (inside the materialized module) the base module is copied to; the draft's `source = "./ratchet-sandbox"`. */
export const BASE_MODULE_DIRNAME = 'ratchet-sandbox';

export const GENERATED_INPUTS_TF = `# Generated by Ratchet. Not part of the draft.
terraform {
  required_version = ">= 1.8.0"

  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.100"
    }
  }
}

# The sandbox this environment lives in (the standard module's contract outputs), injected by Ratchet.
variable "ratchet" {
  type = any
}

provider "aws" {
  region = var.ratchet.region

  default_tags {
    tags = merge(try(var.ratchet.tags, {}), {
      "ratchet:sandbox" = var.ratchet.sandbox_id
      "ratchet:env"     = var.ratchet.environment_hash
      "ratchet:managed" = "opentofu"
    })
  }
}
`;

export const GENERATED_OUTPUTS_TF = `# Generated by Ratchet. Not part of the draft.
output "environment" {
  value = module.${SANDBOX_BASE_MODULE_NAME}.environment
}
`;

/** Join `root` and a relative path from an untrusted file list, refusing anything that leaves `root`. */
function safeJoin(root: string, rel: string): string {
  const n = posix.normalize(rel.replace(/\\/g, '/'));
  if (!n || n.startsWith('/') || n === '..' || n.startsWith('../') || n.includes('\0') || /^[A-Za-z]:/.test(n)) {
    throw new EnvironmentRejectedError([`unsafe path ${JSON.stringify(rel)}`]);
  }
  return join(root, ...n.split('/'));
}

async function writeFiles(root: string, files: ReadonlyArray<{ path: string; content: string }>): Promise<void> {
  for (const f of files) {
    const to = safeJoin(root, f.path);
    await mkdir(dirname(to), { recursive: true });
    await writeFile(to, f.content);
  }
}

/** Throws `EnvironmentRejectedError` unless the files of a DRAFTED environment pass the validator (module-only mode). */
export function assertDraftedEnvironment(env: SandboxEnvironment, opts: { timeLimitSeconds?: number } = {}): void {
  const dir = env.path || DEFAULT_ENVIRONMENT_INFRA_DIR;
  const v = validateEnvironment({
    scope: env.scope,
    moduleOnly: true,
    files: env.files.map((f) => ({ path: `${dir}/${f.path}`, content: f.content })),
    ...(opts.timeLimitSeconds ? { timeLimitSeconds: opts.timeLimitSeconds } : {}),
  });
  // Only the checks that read the module itself decide here; cost is the user's call at approval time.
  const failed = v.checks.filter((c) => !c.ok && c.id !== 'cost' && c.id !== 'scope');
  if (failed.length > 0) throw new EnvironmentRejectedError(failed.map((c) => `${c.label}: ${c.detail}`));
}

/**
 * Writes a drafted environment's module root into `destDir` (recreated) and returns it. `baseModuleDir` is the directory of
 * `infra/modules/sandbox` that ships with the app.
 */
export async function materializeDraftedEnvironment(a: { env: SandboxEnvironment; baseModuleDir: string; destDir: string }): Promise<string> {
  assertDraftedEnvironment(a.env);
  await rm(a.destDir, { recursive: true, force: true });
  await mkdir(a.destDir, { recursive: true });
  await writeFiles(a.destDir, a.env.files);
  const base = join(a.destDir, BASE_MODULE_DIRNAME);
  await mkdir(base, { recursive: true });
  const tf = (await readdir(a.baseModuleDir)).filter((f) => f.endsWith('.tf'));
  if (!tf.includes('main.tf') || !tf.includes('variables.tf')) throw new Error(`base module not found in ${a.baseModuleDir} (expected infra/modules/sandbox)`);
  for (const f of tf) await copyFile(join(a.baseModuleDir, f), join(base, f));
  await writeFile(join(a.destDir, GENERATED_INPUTS_FILE), GENERATED_INPUTS_TF);
  await writeFile(join(a.destDir, GENERATED_OUTPUTS_FILE), GENERATED_OUTPUTS_TF);
  return a.destDir;
}

/** Writes a custom (`infra:`) module into `destDir` (recreated). Refused when it has no .tf files or can run commands here. */
export async function materializeCustomEnvironment(a: { env: SandboxEnvironment; destDir: string }): Promise<string> {
  const tf = a.env.files.filter((f) => f.path.endsWith('.tf'));
  if (tf.length === 0) throw new InfraOverrideError(`infra ${a.env.path} contains no .tf files`);
  for (const f of tf) {
    if (LOCAL_EXEC.test(f.content)) {
      throw new InfraOverrideError(`infra ${a.env.path}/${f.path} can run commands on this machine (local-exec, remote-exec or an external data source); a custom sandbox module may only declare cloud resources`);
    }
  }
  await rm(a.destDir, { recursive: true, force: true });
  await mkdir(a.destDir, { recursive: true });
  await writeFiles(a.destDir, a.env.files);
  return a.destDir;
}

/** The `ratchet` variable the drafted stage is applied with: the standard sandbox's outputs, in the base module's shape. */
export function environmentVars(out: AwsSandboxOutputs, env: SandboxEnvironment, opts: { sandboxId: string; tags?: Record<string, string>; machineImageId?: string; imageVersion?: string }): { ratchet: Record<string, unknown> } {
  return {
    ratchet: {
      sandbox_id: opts.sandboxId,
      region: out.region,
      vpc_id: out.vpcId,
      bench_subnet_id: out.network.benchSubnetId,
      bench_security_group_id: out.network.benchSecurityGroupId,
      artifacts_bucket: out.artifactsBucket,
      eval_instance_profile_name: out.evalIdentity.instanceProfileName,
      environment_hash: env.hash,
      machine_image_id: opts.machineImageId ?? '',
      image_version: opts.imageVersion ?? '',
      tags: opts.tags ?? {},
    },
  };
}

/** `tofu output -json` of the drafted stage + `tofu state list` -> what the environment created. */
export function parseEnvironmentOutputs(env: SandboxEnvironment, outputJson: string, stateList: string): SandboxEnvironmentOutputs {
  const doc = JSON.parse(outputJson) as { environment?: { value?: { machines?: Record<string, { id?: string; role?: string; private_ip?: string }> } } };
  const machines: SandboxEnvironmentOutputs['machines'] = {};
  for (const [name, m] of Object.entries(doc.environment?.value?.machines ?? {})) {
    machines[name] = { id: m.id ?? '', role: m.role ?? 'other', privateIp: m.private_ip ?? '' };
  }
  const resources = stateList
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l !== '' && !l.startsWith('data.') && !l.includes('.data.'));
  return { kind: env.kind, scope: env.scope, hash: env.hash, resources, machines };
}
