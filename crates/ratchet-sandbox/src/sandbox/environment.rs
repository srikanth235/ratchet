//! Materializing an approved environment for OpenTofu (docs/SIMPLIFIED_MODEL.md, "Dynamic environments").
//! (TS `sandbox/environment.ts`)
//!
//! The engine reads the environment's files from the PROTECTED ref and hands them over in
//! [`SandboxInput::environment`](ratchet_core::ports::SandboxInput); nothing here touches git. Two kinds:
//!
//!  - `custom` (`infra:` in ratchet.yaml, advanced): the module REPLACES the standard one. Written to a directory of
//!    its own, refused when it can run commands, and its outputs are checked against infra/contract.md after every
//!    apply.
//!  - `drafted` (`environment.scope` full / single with OpenTofu): a second stage on top of the standard sandbox. The
//!    directory holds the draft's files, a copy of the base module Ratchet ships (`ratchet-sandbox/`) and two
//!    generated files the draft may not contain: the provider / `ratchet` variable (`ratchet_inputs.tf`) and the
//!    `environment` output (`ratchet_outputs.tf`). The drafted files are validated again
//!    ([`ratchet_env::validate_environment`], the same allow-list the user saw) before anything is written.
//!
//! Where the base module comes from: the app ships `infra/modules/sandbox` next to `infra/aws`. The provider's
//! `base_module_dir` option names it; by default it is `../modules/sandbox` relative to the standard module
//! directory (`module_dir`, i.e. `<infra>/aws` -> `<infra>/modules/sandbox`), which is how the daemon lays the
//! bundled `infra/` directory out.

