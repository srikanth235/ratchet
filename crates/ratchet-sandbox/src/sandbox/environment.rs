/// The environment is not allowed to be applied: the problems are the failed checks of the validator.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EnvironmentRejectedError {
    pub problems: Vec<String>,
}

impl fmt::Display for EnvironmentRejectedError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "the environment does not satisfy the sandbox contract:\n - {}\nDraft it again (the setup agent can revise it), or remove environment.scope / infra from ratchet.yaml to use the standard sandbox.",
            self.problems.join("\n - ")
        )
    }
}

impl std::error::Error for EnvironmentRejectedError {}

fn rejected(problems: Vec<String>) -> Error {
    EnvironmentRejectedError { problems }.into()
}

/// Generated next to every drafted environment; the draft may not ship files with these names.
pub const GENERATED_INPUTS_FILE: &str = "ratchet_inputs.tf";
pub const GENERATED_OUTPUTS_FILE: &str = "ratchet_outputs.tf";
/// Directory (inside the materialized module) the base module is copied to; the draft's `source = "./ratchet-sandbox"`.
pub const BASE_MODULE_DIRNAME: &str = "ratchet-sandbox";

pub const GENERATED_INPUTS_TF: &str = r#"# Generated by Ratchet. Not part of the draft.
terraform {
  required_version = ">= 1.8.0"

  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.100"
    }
  }
}

# The sandbox this environment lives in (the standard module's contract outputs), injected by Ratchet.
variable "ratchet" {
  type = any
}

provider "aws" {
  region = var.ratchet.region

  default_tags {
    tags = merge(try(var.ratchet.tags, {}), {
      "ratchet:sandbox" = var.ratchet.sandbox_id
      "ratchet:env"     = var.ratchet.environment_hash
      "ratchet:managed" = "opentofu"
    })
  }
}
"#;

pub const GENERATED_OUTPUTS_TF: &str = r#"# Generated by Ratchet. Not part of the draft.
output "environment" {
  value = module.sandbox.environment
}
"#;

/// Join `root` and a relative path from an untrusted file list, refusing anything that leaves `root`.
fn safe_join(root: &Path, rel: &str) -> Result<PathBuf> {
    let n = posix_normalize(&rel.replace('\\', "/"));
    let b = n.as_bytes();
    let drive = b.len() >= 2 && b[0].is_ascii_alphabetic() && b[1] == b':';
    if n.is_empty()
        || n.starts_with('/')
        || n == ".."
        || n.starts_with("../")
        || n.contains('\0')
        || drive
    {
        return Err(rejected(vec![format!("unsafe path {}", json_str(rel))]));
    }
    Ok(n.split('/').fold(root.to_path_buf(), |p, s| p.join(s)))
}

async fn write_files(root: &Path, files: &[(&str, &str)]) -> Result<()> {
    for (path, content) in files {
        let to = safe_join(root, path)?;
        if let Some(parent) = to.parent() {
            tokio::fs::create_dir_all(parent).await?;
        }
        tokio::fs::write(&to, content).await?;
    }
    Ok(())
}

/// Fails with [`EnvironmentRejectedError`] unless the files of a DRAFTED environment pass the validator (module-only
/// mode). Only the checks that read the module itself decide here; cost and scope are the user's call at approval time.
pub fn assert_drafted_environment(
    env: &SandboxEnvironment,
    time_limit_seconds: Option<f64>,
) -> Result<()> {
    let dir = if env.path.is_empty() {
        DEFAULT_ENVIRONMENT_INFRA_DIR
    } else {
        env.path.as_str()
    };
    let mut input = ValidateEnvironmentInput::new(
        env.scope,
        env.files
            .iter()
            .map(|f| EnvironmentFile::new(format!("{dir}/{}", f.path), f.content.clone()))
            .collect(),
    );
    input.module_only = true;
    input.time_limit_seconds = time_limit_seconds;
    let v = validate_environment(&input);
    let failed: Vec<String> = v
        .checks
        .iter()
        .filter(|c| !c.ok && c.id != "cost" && c.id != "scope")
        .map(|c| format!("{}: {}", c.label, c.detail))
        .collect();
    if failed.is_empty() {
        Ok(())
    } else {
        Err(rejected(failed))
    }
}

/// Writes a drafted environment's module root into `dest_dir` (recreated) and returns it. `base_module_dir` is the
/// directory of `infra/modules/sandbox` that ships with the app.
pub async fn materialize_drafted_environment(
    env: &SandboxEnvironment,
    base_module_dir: &Path,
    dest_dir: &Path,
) -> Result<PathBuf> {
    assert_drafted_environment(env, None)?;
    let _ = tokio::fs::remove_dir_all(dest_dir).await;
    tokio::fs::create_dir_all(dest_dir).await?;
    let files: Vec<(&str, &str)> = env
        .files
        .iter()
        .map(|f| (f.path.as_str(), f.content.as_str()))
        .collect();
    write_files(dest_dir, &files).await?;
    let base = dest_dir.join(BASE_MODULE_DIRNAME);
    tokio::fs::create_dir_all(&base).await?;
    let mut tf = Vec::new();
    let mut rd = tokio::fs::read_dir(base_module_dir).await?;
    while let Some(e) = rd.next_entry().await? {
        let name = e.file_name().to_string_lossy().into_owned();
        if name.ends_with(".tf") {
            tf.push(name);
        }
    }
    if !tf.iter().any(|f| f == "main.tf") || !tf.iter().any(|f| f == "variables.tf") {
        return Err(Error::other(format!(
            "base module not found in {} (expected infra/modules/sandbox)",
            base_module_dir.display()
        )));
    }
    for f in &tf {
        tokio::fs::copy(base_module_dir.join(f), base.join(f)).await?;
    }
    tokio::fs::write(dest_dir.join(GENERATED_INPUTS_FILE), GENERATED_INPUTS_TF).await?;
    tokio::fs::write(dest_dir.join(GENERATED_OUTPUTS_FILE), GENERATED_OUTPUTS_TF).await?;
    Ok(dest_dir.to_path_buf())
}

/// Writes a custom (`infra:`) module into `dest_dir` (recreated). Refused when it has no .tf files or can run commands
/// here.
pub async fn materialize_custom_environment(
    env: &SandboxEnvironment,
    dest_dir: &Path,
) -> Result<PathBuf> {
    let tf: Vec<_> = env
        .files
        .iter()
        .filter(|f| f.path.ends_with(".tf"))
        .collect();
    if tf.is_empty() {
        return Err(InfraOverrideError(format!("infra {} contains no .tf files", env.path)).into());
    }
    for f in &tf {
        if LOCAL_EXEC.is_match(&f.content) {
            return Err(InfraOverrideError(format!(
                "infra {}/{} can run commands on this machine (local-exec, remote-exec or an external data source); a custom sandbox module may only declare cloud resources",
                env.path, f.path
            ))
            .into());
        }
    }
    let _ = tokio::fs::remove_dir_all(dest_dir).await;
    tokio::fs::create_dir_all(dest_dir).await?;
    let files: Vec<(&str, &str)> = env
        .files
        .iter()
        .map(|f| (f.path.as_str(), f.content.as_str()))
        .collect();
    write_files(dest_dir, &files).await?;
    Ok(dest_dir.to_path_buf())
}

#[derive(Debug, Clone, Default)]
pub struct EnvironmentVarsOptions {
    pub sandbox_id: String,
    pub tags: Option<std::collections::BTreeMap<String, String>>,
    pub machine_image_id: Option<String>,
    pub image_version: Option<String>,
}

/// The `ratchet` variable the drafted stage is applied with: the standard sandbox's outputs, in the base module's
/// shape. Never the agent side, never the holdout identity.
pub fn environment_vars(
    out: &SandboxOutputs,
    env: &SandboxEnvironment,
    opts: &EnvironmentVarsOptions,
) -> Value {
    json!({
        "ratchet": {
            "sandbox_id": opts.sandbox_id,
            "region": out.region,
            "vpc_id": out.vpc_id,
            "bench_subnet_id": out.network.bench_subnet_id,
            "bench_security_group_id": out.network.bench_security_group_id,
            "artifacts_bucket": out.artifacts_bucket,
            "eval_instance_profile_name": out.eval_identity.instance_profile_name,
            "environment_hash": env.hash,
            "machine_image_id": opts.machine_image_id.clone().unwrap_or_default(),
            "image_version": opts.image_version.clone().unwrap_or_default(),
            "tags": opts.tags.clone().unwrap_or_default(),
        }
    })
}

/// `tofu output -json` of the drafted stage + `tofu state list` -> what the environment created.
pub fn parse_environment_outputs(
    env: &SandboxEnvironment,
    output_json: &str,
    state_list: &str,
) -> Result<SandboxEnvironmentOutputs> {
    let doc: Value = serde_json::from_str(output_json)?;
    let mut machines = std::collections::BTreeMap::new();
    let empty = Map::new();
    let found = doc
        .pointer("/environment/value/machines")
        .and_then(Value::as_object)
        .unwrap_or(&empty);
    for (name, m) in found {
        let s = |k: &str, d: &str| m.get(k).and_then(Value::as_str).unwrap_or(d).to_string();
        machines.insert(
            name.clone(),
            SandboxEnvironmentMachine {
                id: s("id", ""),
                role: s("role", "other"),
                private_ip: s("private_ip", ""),
            },
        );
    }
    let resources = state_list
        .split('\n')
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with("data.") && !l.contains(".data."))
        .map(str::to_owned)
        .collect();
    Ok(SandboxEnvironmentOutputs {
        kind: env.kind,
        scope: env.scope,
        hash: env.hash.clone(),
        resources,
        machines,
    })
}

/// True for the drafted kind.
pub(crate) fn is_drafted(env: &SandboxEnvironment) -> bool {
    env.kind == SandboxEnvironmentKind::Drafted
}
