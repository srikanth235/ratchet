//! Making `node` resolve for evaluator, setup and guardrail commands (port of `node-path.ts`).
//!
//! Evaluator, setup and guardrail commands are shell strings such as `node dist/eval/backtest.js`. They need a `node` on PATH
//! that works, and two things break that:
//!  - inside the packaged Electron app (launched from the Dock) PATH is the bare launchd PATH and has no node at all;
//!  - `process.execPath` there is the Electron binary, which only behaves like Node with `ELECTRON_RUN_AS_NODE=1` in its
//!    environment.
//!
//! [`with_node_on_path`] fixes both by putting a directory with a `node` executable first on PATH. The Rust engine is not an
//! Electron app, so the "current runtime" is simply the first `node` on PATH (and PATH is then left alone); the Electron
//! cases are kept for a host that embeds the engine in one and passes its runtime explicitly.

use std::collections::HashMap;
use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::sync::{LazyLock, Mutex};

use indexmap::IndexMap;

/// What the fix depends on; a parameter (not read from the process) so tests can simulate Electron.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NodeRuntimeInfo {
    /// `process.execPath`.
    pub exec_path: PathBuf,
    /// `process.versions.electron`; set only when running inside Electron.
    pub electron: Option<String>,
    /// Anything but `win32` is treated as POSIX.
    pub platform: Option<String>,
}

impl NodeRuntimeInfo {
    pub fn plain(exec_path: impl Into<PathBuf>) -> Self {
        NodeRuntimeInfo {
            exec_path: exec_path.into(),
            electron: None,
            platform: Some("linux".into()),
        }
    }

    pub fn electron(exec_path: impl Into<PathBuf>, version: impl Into<String>) -> Self {
        NodeRuntimeInfo {
            exec_path: exec_path.into(),
            electron: Some(version.into()),
            platform: Some("linux".into()),
        }
    }
}

/// How the local runner makes `node` resolve.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub enum NodeRuntime {
    /// The first `node` on PATH (PATH is left alone when there is one).
    #[default]
    Current,
    /// Leave PATH alone.
    Disabled,
    /// A specific runtime (an embedding Electron app, a test).
    Explicit(NodeRuntimeInfo),
}

fn path_separator() -> char {
    ':'
}

fn is_executable(p: &Path) -> bool {
    fs::metadata(p).is_ok_and(|m| m.is_file() && m.permissions().mode() & 0o111 != 0)
}

/// The `node` that `path_env` would resolve (symlinks resolved), or `None`.
pub fn resolve_node_on_path(path_env: &str) -> Option<PathBuf> {
    for dir in path_env.split(path_separator()) {
        if dir.is_empty() {
            continue;
        }
        let candidate = Path::new(dir).join("node");
        if is_executable(&candidate)
            && let Ok(real) = fs::canonicalize(&candidate)
        {
            return Some(real);
        }
    }
    None
}

/// The runtime to assume when nothing is said: the `node` on this process's PATH, if any.
pub fn current_node_runtime() -> Option<NodeRuntimeInfo> {
    let path = std::env::var("PATH").unwrap_or_default();
    resolve_node_on_path(&path).map(NodeRuntimeInfo::plain)
}

fn shq(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// Body of the `node` shim. Under Electron the variable is set for that one process only, not exported to anything else.
pub fn node_shim_script(exec_path: &str, electron: bool) -> String {
    format!(
        "#!/bin/sh\n# Generated by Ratchet: makes `node` resolve to the runtime that is running the app.\n{}exec {} \"$@\"\n",
        if electron { "ELECTRON_RUN_AS_NODE=1 " } else { "" },
        shq(exec_path)
    )
}

static SHIM_DIRS: LazyLock<Mutex<HashMap<String, PathBuf>>> =
    LazyLock::new(|| Mutex::new(HashMap::new()));

/// A directory holding an executable `node` shim for `exec_path`. It is created once per process under a fresh random
/// directory (mode 0700, so nobody can pre-plant a `node` in a predictable /tmp path). Shim directories are removed by
/// [`cleanup_node_shims`] (the TypeScript removed them on process exit; Rust has no exit hook, so a host calls it on
/// shutdown).
pub fn ensure_node_shim(
    exec_path: &Path,
    electron: bool,
    shim_root: Option<&Path>,
) -> std::io::Result<PathBuf> {
    let root = shim_root.map_or_else(std::env::temp_dir, Path::to_path_buf);
    let key = format!("{}\0{}\0{electron}", root.display(), exec_path.display());
    let mut dirs = SHIM_DIRS.lock().unwrap_or_else(|e| e.into_inner());
    if let Some(known) = dirs.get(&key) {
        if is_executable(&known.join("node")) {
            return Ok(known.clone());
        }
        dirs.remove(&key); // removed behind our back (tmp cleaner): recreate
    }
    let dir = tempfile::Builder::new()
        .prefix("ratchet-node-")
        .tempdir_in(&root)?
        .keep();
    fs::set_permissions(&dir, fs::Permissions::from_mode(0o700))?;
    let file = dir.join("node");
    fs::write(&file, node_shim_script(&exec_path.to_string_lossy(), electron))?;
    fs::set_permissions(&file, fs::Permissions::from_mode(0o755))?;
    dirs.insert(key, dir.clone());
    Ok(dir)
}

/// Remove every shim directory this process created.
pub fn cleanup_node_shims() {
    let mut dirs = SHIM_DIRS.lock().unwrap_or_else(|e| e.into_inner());
    for (_, d) in dirs.drain() {
        let _ = fs::remove_dir_all(d);
    }
}

/// The directory to put first on PATH so that `node` runs this runtime, or `None` when PATH is already fine:
///  - Electron: always a shim that execs the Electron binary with `ELECTRON_RUN_AS_NODE=1`;
///  - plain Node whose binary is called `node`: `dirname(exec_path)`, unless the first `node` on PATH already is that binary
///    (then PATH is left alone, so tools in that directory cannot shadow others);
///  - plain Node under another name (`node22`, ...): a shim, so `node` exists at all.
pub fn node_dir_for(
    runtime: &NodeRuntimeInfo,
    path_env: &str,
    shim_root: Option<&Path>,
) -> Option<PathBuf> {
    if runtime.platform.as_deref() == Some("win32") {
        return None;
    }
    if runtime.electron.is_some() {
        return ensure_node_shim(&runtime.exec_path, true, shim_root).ok();
    }
    let me = fs::canonicalize(&runtime.exec_path).unwrap_or_else(|_| runtime.exec_path.clone());
    if resolve_node_on_path(path_env).as_deref() == Some(me.as_path()) {
        return None;
    }
    if runtime.exec_path.file_name().is_some_and(|n| n == "node") {
        return runtime.exec_path.parent().map(Path::to_path_buf);
    }
    ensure_node_shim(&runtime.exec_path, false, shim_root).ok()
}

#[derive(Debug, Clone, Default)]
pub struct WithNodeOnPathOptions {
    pub runtime: Option<NodeRuntimeInfo>,
    /// Where shim directories are created. Default: the OS temp dir.
    pub shim_root: Option<PathBuf>,
    /// PATH to extend when `env` has none. Default: this process's PATH.
    pub base_path: Option<String>,
}

/// `env` with `PATH` prefixed so that `node` works. Does not mutate `env`. With no runtime (neither given nor found on this
/// process's PATH) `env` is returned as is.
pub fn with_node_on_path(
    env: &IndexMap<String, String>,
    opts: &WithNodeOnPathOptions,
) -> IndexMap<String, String> {
    let mut out = env.clone();
    let base = out
        .get("PATH")
        .cloned()
        .or_else(|| opts.base_path.clone())
        .or_else(|| std::env::var("PATH").ok())
        .unwrap_or_default();
    let Some(runtime) = opts.runtime.clone().or_else(current_node_runtime) else {
        return out;
    };
    let Some(dir) = node_dir_for(&runtime, &base, opts.shim_root.as_deref()) else {
        return out;
    };
    let dir = dir.to_string_lossy().into_owned();
    out.insert(
        "PATH".into(),
        if base.is_empty() {
            dir
        } else {
            format!("{dir}{}{base}", path_separator())
        },
    );
    out
}
